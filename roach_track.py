import sys, json, time, csv, threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import serial

PORT = sys.argv[1]
BAUD = 921600

# Target zones: name -> (x, y, w, h), top-left corner, in image pixels
TARGETS = {"T1": (20, 20, 60, 60), "T2": (160, 20, 60, 60), "T3": (90, 150, 60, 60)}
MIN_SCORE = 40
LEG_CLASS = None        # leg's class id, or None to accept any class
MIN_OVERLAP = 0.0       # fraction of a target covered; 0.0 means any overlap counts

state = {"json": "{}"}
lock = threading.Lock()

def overlap(t, cx, cy, w, h):
    tx, ty, tw, th = t
    lx, ly = cx - w / 2, cy - h / 2
    ix = min(tx + tw, lx + w) - max(tx, lx)
    iy = min(ty + th, ly + h) - max(ty, ly)
    return 0.0 if ix <= 0 or iy <= 0 else (ix * iy) / (tw * th)

def worker():
    ser = serial.Serial(PORT, BAUD, timeout=2)
    time.sleep(1)
    ser.reset_input_buffer()
    out = open("leg_track.csv", "w", newline="")
    w = csv.writer(out)
    w.writerow(["time_s", "leg_x", "leg_y", "score"] + [f"overlap_{n}" for n in TARGETS])
    t0 = time.time()
    frame = 0
    counts = {n: 0 for n in TARGETS}
    printed_keys = False

    while True:
        ser.write(b"AT+INVOKE=1,0,0\r\n")   # 1 run, no filter, include image
        deadline = time.time() + 5
        obj = None
        while time.time() < deadline:
            line = ser.readline().decode(errors="ignore").strip()
            i = line.find("{")
            if i < 0:
                continue
            try:
                o = json.loads(line[i:])
            except json.JSONDecodeError:
                continue
            if o.get("name") == "INVOKE" and isinstance(o.get("data"), dict) and "boxes" in o["data"]:
                obj = o
                break
        if obj is None:
            continue
        data = obj["data"]
        if not printed_keys:
            print("Reply fields:", list(data.keys()))
            printed_keys = True

        frame += 1
        boxes = [b for b in data["boxes"]
                 if b[4] >= MIN_SCORE and (LEG_CLASS is None or b[5] == LEG_CLASS)]
        best = max(boxes, key=lambda b: b[4]) if boxes else None

        ov = [overlap(t, best[0], best[1], best[2], best[3]) if best else 0.0
              for t in TARGETS.values()]
        hits = [1 if (o > MIN_OVERLAP or (MIN_OVERLAP == 0 and o > 0)) else 0 for o in ov]
        for n, h in zip(TARGETS, hits):
            counts[n] += h

        w.writerow([round(time.time() - t0, 3),
                    best[0] if best else "", best[1] if best else "",
                    best[4] if best else ""] + [round(o, 2) for o in ov])
        out.flush()

        payload = {
            "frame": frame,
            "img": data.get("image", ""),
            "boxes": [{"x": b[0], "y": b[1], "w": b[2], "h": b[3], "s": b[4]} for b in data["boxes"]],
            "targets": [{"n": n, "x": t[0], "y": t[1], "w": t[2], "h": t[3]} for n, t in TARGETS.items()],
            "hits": hits,
            "counts": list(counts.values()),
            "leg": {"x": best[0], "y": best[1]} if best else None,
        }
        with lock:
            state["json"] = json.dumps(payload)

PAGE = """<!doctype html><html><body style="background:#111;color:#eee;font-family:sans-serif">
<h3>Roach leg tracker</h3>
<canvas id="c" width="640" height="640" style="border:1px solid #555"></canvas>
<div><button onclick="trail=[]">Clear trail</button> <span id="info"></span></div>
<script>
const c=document.getElementById('c'),g=c.getContext('2d'),info=document.getElementById('info');
let trail=[];
async function loop(){
  try{
    const d=await (await fetch('/data')).json();
    if(!d.img){info.textContent='waiting for frame...';setTimeout(loop,300);return;}
    const img=new Image();
    img.onload=()=>{
      const sx=c.width/img.naturalWidth, sy=c.height/img.naturalHeight;
      g.drawImage(img,0,0,c.width,c.height);
      d.targets.forEach((t,i)=>{
        g.lineWidth=3; g.strokeStyle=d.hits[i]?'#0f0':'#f33';
        g.strokeRect(t.x*sx,t.y*sy,t.w*sx,t.h*sy);
        g.fillStyle=g.strokeStyle; g.font='14px sans-serif'; g.fillText(t.n,t.x*sx+3,t.y*sy+14);
      });
      d.boxes.forEach(b=>{
        g.strokeStyle='#ff0'; g.lineWidth=2;
        g.strokeRect((b.x-b.w/2)*sx,(b.y-b.h/2)*sy,b.w*sx,b.h*sy);
      });
      if(d.leg) trail.push([d.leg.x*sx,d.leg.y*sy]);
      g.fillStyle='#0f0';
      trail.forEach(p=>{g.beginPath();g.arc(p[0],p[1],2,0,6.3);g.fill();});
      info.textContent='frame '+d.frame+' | hit frames per target: '+d.counts.join(', ');
    };
    img.src='data:image/jpeg;base64,'+d.img;
  }catch(e){info.textContent='error: '+e;}
  setTimeout(loop,50);
}
loop();
</script></body></html>"""

class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        if self.path == "/data":
            with lock:
                body = state["json"].encode()
            ctype = "application/json"
        else:
            body = PAGE.encode()
            ctype = "text/html"
        self.send_response(200)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)
    def log_message(self, *a):
        pass

threading.Thread(target=worker, daemon=True).start()
print("Open http://localhost:8000  (Ctrl+C to stop)")
ThreadingHTTPServer(("127.0.0.1", 8000), Handler).serve_forever()